export function normalizeDigimonTerm(value = "") {
  return String(value ?? "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[-_]+/g, " ")
    .replace(/[^a-zA-Z0-9+ ]+/g, "")
    .replace(/\s+/g, " ")
    .toLowerCase()
    .trim();
}

export function getDigimonTermLanguage() {
  const lang = String(game.i18n?.lang ?? "en").toLowerCase();
  return lang.startsWith("pt") ? "pt" : "en";
}

export function getDigimonTermLabel(kind = "types", value = "") {
  const raw = String(value ?? "").trim();
  if (!raw) return "";

  const key = normalizeDigimonTerm(raw);
  const dictionary = kind === "groups"
    ? DDA_DIGIMON_GROUP_TERMS
    : DDA_DIGIMON_TYPE_TERMS;

  const entry = dictionary[key];

  if (!entry) return raw;

  const lang = getDigimonTermLanguage();

  return entry[lang] ?? entry.en ?? entry.pt ?? raw;
}

export function getDigimonTypeLabel(value = "") {
  return getDigimonTermLabel("types", value);
}

export function getDigimonGroupLabel(value = "") {
  return getDigimonTermLabel("groups", value);
}

export function getDigimonNameStyle() {
  try {
    return game.settings.get(MODULE_ID, "digimonNameStyle") || DIGIMON_NAME_STYLES.original;
  } catch (_error) {
    return DIGIMON_NAME_STYLES.original;
  }
}

export function getDigimonNameData(actorOrData = null) {
  const system = actorOrData?.system ?? actorOrData ?? {};
  const names = system.names ?? actorOrData?.names ?? {};
  const sourceId = String(system.sourceId ?? actorOrData?.sourceId ?? "").trim();
  const species = String(system.species ?? actorOrData?.species ?? actorOrData?.name ?? "").trim();
  const actorName = String(actorOrData?.name ?? "").trim();

  const lookupKeys = [
    sourceId,
    names.canonical,
    names.original,
    names.dub,
    species,
    actorName
  ]
    .map((value) => normalizeDigimonTerm(value))
    .filter(Boolean);

  for (const key of lookupKeys) {
    if (DDA_DIGIMON_NAME_ALIASES[key]) {
      return {
        ...DDA_DIGIMON_NAME_ALIASES[key],
        canonical: DDA_DIGIMON_NAME_ALIASES[key].id
      };
    }
  }

  return {
    id: sourceId || normalizeDigimonTerm(species || actorName).replace(/\s+/g, "_"),
    canonical: sourceId || normalizeDigimonTerm(species || actorName).replace(/\s+/g, "_"),
    original: names.original || species || actorName,
    dub: names.dub || names.original || species || actorName,
    aliases: Array.isArray(names.aliases) ? names.aliases : []
  };
}

export function getDigimonDisplayName(actorOrData = null) {
  const style = getDigimonNameStyle();
  const data = getDigimonNameData(actorOrData);

  return data[style] || data.original || data.dub || "";
}

export function getDigimonOriginalName(actorOrData = null) {
  return getDigimonNameData(actorOrData).original || "";
}

export function getDigimonDubName(actorOrData = null) {
  return getDigimonNameData(actorOrData).dub || "";
}

export function getDigimonAliases(actorOrData = null) {
  return getDigimonNameData(actorOrData).aliases ?? [];
}

export function isPersistentPartner(actorOrData = null) {
  const system = actorOrData?.system ?? actorOrData ?? {};

  return Boolean(
    system.isPersistentPartner ||
    system.partner?.persistent ||
    system.persistentPartner
  );
}

export function getDigimonSheetDisplayName(actorOrData = null) {
  const actorName = String(actorOrData?.name ?? "").trim();

  if (isPersistentPartner(actorOrData) && actorName) {
    return actorName;
  }

  return getDigimonDisplayName(actorOrData);
}