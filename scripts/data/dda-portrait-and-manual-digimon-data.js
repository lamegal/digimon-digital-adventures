function ensureEvolutionIndex(actor = {}) {
  actor.system ??= {};
  actor.system.evolutionIndex ??= {};

  for (const key of [
    "normalFrom",
    "normalTo",
    "candidateFrom",
    "candidateTo",
    "specialFrom",
    "specialTo",
    "candidateSpecialFrom",
    "candidateSpecialTo",
    "unresolvedFrom",
    "unresolvedTo",
    "rawFrom",
    "rawTo"
  ]) {
    if (!Array.isArray(actor.system.evolutionIndex[key])) {
      actor.system.evolutionIndex[key] = [];
    }
  }

  actor.system.evolutionHints ??= {};
  if (!Array.isArray(actor.system.evolutionHints.evolvesFrom)) {
    actor.system.evolutionHints.evolvesFrom = [];
  }
  if (!Array.isArray(actor.system.evolutionHints.evolvesTo)) {
    actor.system.evolutionHints.evolvesTo = [];
  }

  return actor.system.evolutionIndex;
}

function addUnique(array, value) {
  if (!Array.isArray(array) || !value) return;
  if (!array.includes(value)) array.push(value);
}

function makeRelationReference(actor = {}, relationType = "normal", rank = "primary") {
  const system = actor.system ?? {};

  return {
    key: sourceIdOf(actor),
    name: actor.name || system.species || sourceIdOf(actor),
    stage: system.stage || "",
    evolutionCategory: system.evolutionCategory || "normal",
    folderPath: system.folderPath || system.stage || "",
    img: actor.img || system.images?.portrait || "icons/svg/mystery-man.svg",
    relationType,
    rank
  };
}

function attachManualRelation(fromActor, toActor, relation) {
  const fromIndex = ensureEvolutionIndex(fromActor);
  const toIndex = ensureEvolutionIndex(toActor);

  const fromId = sourceIdOf(fromActor);
  const toId = sourceIdOf(toActor);

  if (!fromIndex.normalTo.some((entry) => entry?.key === toId)) {
    fromIndex.normalTo.push(makeRelationReference(toActor, "normal", relation.rank));
  }

  if (!toIndex.normalFrom.some((entry) => entry?.key === fromId)) {
    toIndex.normalFrom.push(makeRelationReference(fromActor, "normal", relation.rank));
  }

  addUnique(fromActor.system.evolutionHints.evolvesTo, toId);
  addUnique(toActor.system.evolutionHints.evolvesFrom, fromId);

  addUnique(fromIndex.rawTo, toId);
  addUnique(toIndex.rawFrom, fromId);
}

function applyPortraitMetadata(actor = {}) {
  actor.system ??= {};
  const system = actor.system;
  const names = system.names ?? {};

  const portraitPath = getDdaPortraitPath({
    key: system.sourceId || names.canonical || actor.databaseId || "",
    name: actor.name || "",
    species: system.species || "",
    aliases: names.aliases ?? []
  });

  if (portraitPath) {
    system.images ??= {};
    system.images.portraitImagePath = portraitPath;
  }

  return actor;
}

export function applyDdaPortraitAndManualDigimonData(rawActors = []) {
  const actors = Array.isArray(rawActors)
    ? rawActors.map((actor) => clone(actor))
    : [];

  const bySourceId = new Map(
    actors
      .map((actor) => [sourceIdOf(actor), actor])
      .filter(([id]) => Boolean(id))
  );

  for (const manualActor of DDA_MANUAL_DIGIMON_ACTORS) {
    const id = sourceIdOf(manualActor);
    if (bySourceId.has(id)) continue;

    const copied = clone(manualActor);
    actors.push(copied);
    bySourceId.set(id, copied);
  }

  for (const relation of DDA_MANUAL_LINE) {
    const fromActor = bySourceId.get(relation.fromId);
    const toActor = bySourceId.get(relation.toId);

    if (!fromActor || !toActor) {
      console.warn("DDA | Manual evolution relation skipped because one Actor is missing.", relation);
      continue;
    }

    attachManualRelation(fromActor, toActor, relation);
  }

  return actors.map((actor) => applyPortraitMetadata(actor));
}
